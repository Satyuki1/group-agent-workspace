import test from 'node:test';
import assert from 'node:assert/strict';
import {progressProjector,taskOpening} from '../src/task-progress.mjs';
const user=(seq,id)=>({seq,type:'user/message',data:{source:{rpcId:id}}});
const task={id:'task',baseline_cursor:10,progress:{}};
const live=(index,chunk)=>({type:'assistant-stream',frame:{type:'chunk',attemptId:'a',index,chunk}});
test('progress is gated by the exact task, streams text and excludes raw reasoning',()=>{
  const p=progressProjector(task);
  p.accept({type:'snapshot',records:[{event:user(1,'old')},{event:{seq:5,type:'assistant/message',data:{message:{content:[{type:'text',text:'私人旧内容'}]}}}}]});
  p.accept(live(0,{type:'text-delta',index:0,text:'不属于本任务'}));
  assert.equal(p.snapshot().text,'');
  p.accept({type:'event',event:user(11,'task')});
  p.accept({type:'assistant-stream',frame:{type:'start',attemptId:'a',startedAfterSeq:11}});
  p.accept({type:'event',event:{seq:12,type:'user/message',data:{source:{kind:'time-context',sections:[{text:'系统上下文'}]}}}});
  p.accept(live(0,{type:'reasoning-delta',index:0,text:'不公开的推理正文'}));
  assert.equal(p.snapshot().phase,'thinking');assert.ok(!JSON.stringify(p.snapshot()).includes('不公开'));
  p.accept(live(1,{type:'text-delta',index:1,text:'第一段'}));
  assert.equal(p.snapshot().text,'第一段');
  p.accept(live(1,{type:'text-delta',index:1,text:'重复帧'}));
  p.accept(live(2,{type:'text-delta',index:2,text:'第二段'}));
  p.accept(live(3,{type:'block-end',index:2,block:{type:'text',text:'第二段'}}));
  assert.equal(p.snapshot().text,'第一段\n第二段');
  p.accept({type:'event',event:user(20,'next-task')});p.accept(live(4,{type:'text-delta',index:1,text:'下一任务'}));
  assert.ok(!p.snapshot().text.includes('下一任务'));
});
test('durable tools pair input/result, redact credentials and replay without duplicates',()=>{
  const p=progressProjector(task);
  const records=[user(11,'task'),{seq:12,type:'tool/call',data:{callId:'call',name:'read',arguments:JSON.stringify({path:'/work/a.md',apiKey:'secret'})}},{seq:13,type:'tool/result',data:{message:{toolCallId:'call',isError:true,content:[{type:'text',text:'失败 Bearer secret-value'}]}}}].map(event=>({event}));
  p.accept({type:'snapshot',records});p.accept({type:'snapshot',records});
  const tools=p.snapshot().tools;assert.equal(tools.length,1);assert.equal(tools[0].state,'failed');assert.match(tools[0].input,/a.md/);
  assert.ok(!JSON.stringify(tools).includes('secret'));assert.ok(!JSON.stringify(tools).includes('Bearer'));
  p.accept({type:'snapshot',records:[]});assert.equal(p.snapshot().tools.length,1);assert.equal(p.snapshot().phase,'reconnecting');
});
test('reconnect pins the observed cut and pages back to the exact task before live replay',async()=>{
  const frame={type:'snapshot',cursor:300,hasMore:true,records:[{event:{seq:299,type:'assistant/message',data:{message:{content:[{type:'text',text:'已有进度'}]}}}}],assistantStream:{activeAttempt:{attemptId:'a',startedAfterSeq:300,nextIndex:0,stream:[]}}};
  const requests=[];
  const opening=await taskOpening(frame,task,async request=>{requests.push(request);return {hasMore:false,records:[{event:user(11,'task')},{event:{seq:12,type:'step/start',data:{}}}]};});
  assert.equal(requests[0].throughSeq,300);assert.equal(requests[0].beforeSeq,299);
  const p=progressProjector(task);p.accept(opening);p.accept(live(0,{type:'text-delta',index:0,text:'重连后的新内容'}));
  assert.equal(p.snapshot().text,'重连后的新内容');
  assert.ok(!JSON.stringify(opening).includes('request/header'));
});
test('long tool parameters remain a redacted excerpt after reconnect and settlement',async()=>{
  const call={seq:12,type:'tool/call',data:{callId:'long',name:'write',arguments:JSON.stringify({file_path:'/work/long.md',password:'secret-value',content:'x'.repeat(2500)})}};
  const initial={type:'snapshot',cursor:12,hasMore:false,records:[{event:user(11,'task')},{event:call}]};
  const p=progressProjector(task);p.accept({type:'event',event:user(11,'task')});p.accept({type:'event',event:call});
  const liveInput=p.snapshot().tools[0].input;assert.equal(liveInput.length,1000);
  p.accept(await taskOpening(initial,task,()=>{throw Error('unexpected page');}));
  assert.equal(p.snapshot().tools[0].input,liveInput);assert.match(liveInput,/long.md/);assert.ok(!liveInput.includes('secret-value'));assert.notEqual(liveInput,'参数正在生成');
});
